def merge_extra(base: dict[str, dict[str, str]], extra: dict[str, dict[str, str]]) -> None:
    """In-place merge of extra lang maps into base catalog dicts."""
    for source, by_lang in extra.items():
        table = base.setdefault(source, {})
        for lang, text in by_lang.items():
            table.setdefault(lang, text)
